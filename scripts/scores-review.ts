// Generates docs/SCORES_REVIEW.md from the data and the persona fixtures.
// Run: npm run scores:review   (add --print to also print the persona summary)
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { rawData } from '../src/data/raw'
import { AXIS_IDS } from '../src/data/schemas'
import { parseGameData } from '../src/data/validate'
import { rank } from '../src/engine/rank'
import { ENGINE_VERSION } from '../src/engine/config'
import { PERSONAS } from '../src/engine/personas'

const data = parseGameData(rawData)
const axes = new Map(data.axes.map((a) => [a.id, a]))
const builds = new Map(data.builds.map((b) => [b.id, b]))
const races = new Map(data.races.map((r) => [r.id, r]))
const name = (id: string) => builds.get(id)?.name ?? id
const fmt = (n: number) => (Number.isInteger(n) ? `${n}` : n.toFixed(1))

const lines: string[] = []
const out = (s = '') => lines.push(s)

out('# Scores review — draft for your review')
out()
out(`> Generated by \`npm run scores:review\` from \`src/data/builds.json\` (data v${data.meta.dataVersion}, engine v${ENGINE_VERSION}, game state: ${data.meta.gameState}).`)
out('> Do not edit this file by hand. Change the numbers in `builds.json` (or tell me, e.g. "Frost Mage gold 4 → 3") and regenerate.')
out()
out('All scores are **editorial**: our judgment from Classic-era experience (an assumption, not a Forever fact), adjusted for the')
out('Forever beta changes in `docs/RESEARCH.md`. Raid scores are speculative until raids open on Dec 9, and their weight is')
out('reduced by 30% in the engine. `*` marks an axis we are less sure about for that build.')
out()
out('## Scale')
out()
out('| Axis | 0 = | 5 = | Mode |')
out('|---|---|---|---|')
for (const id of AXIS_IDS) {
  const a = axes.get(id)!
  out(`| **${a.label}** (${a.short}) | ${a.low} | ${a.high} | ${a.mode === 'closeness' ? 'closer is better' : 'more is fine'} |`)
}
out()
out('## All builds')
out()
out(`| Build | Role | ${AXIS_IDS.map((id) => axes.get(id)!.short).join(' | ')} | Conf. |`)
out(`|---|---|${AXIS_IDS.map(() => '--:').join('|')}|---|`)
for (const b of data.builds) {
  const cells = AXIS_IDS.map((id) => fmt(b.axes[id]) + (b.lowConfidenceAxes.includes(id) ? '*' : ''))
  out(`| ${b.name} | ${b.role} | ${cells.join(' | ')} | ${b.confidence} |`)
}
out()
out('## Highest and lowest per axis')
out()
out('A quick sanity check: do these extremes look right to you?')
out()
out('| Axis | Highest | Lowest |')
out('|---|---|---|')
for (const id of AXIS_IDS) {
  const sorted = [...data.builds].sort((x, y) => y.axes[id] - x.axes[id])
  const top = sorted.slice(0, 3).map((b) => `${b.name} ${fmt(b.axes[id])}`).join(', ')
  const bottom = sorted.slice(-3).reverse().map((b) => `${b.name} ${fmt(b.axes[id])}`).join(', ')
  out(`| ${axes.get(id)!.label} | ${top} | ${bottom} |`)
}
out()
out('## Persona check')
out()
out('What the engine recommends for the test personas (`src/engine/personas.ts`). Match % is calibrated so a great fit')
out('lands around 85–97%. If a list looks wrong to a WoW player, the scores above (or the weights) need adjusting.')
out()
const summary: string[] = []
for (const p of PERSONAS) {
  const result = rank(p.answers, data)
  out(`### ${p.label}`)
  out()
  out('| # | Build | Match | Best races | Dual spec |')
  out('|--:|---|--:|---|---|')
  for (const r of result.results.slice(0, 5)) {
    const raceNames = r.races.map((x) => `${races.get(x.raceId)?.name ?? x.raceId}${x.newInForever ? ' ★' : ''}`).join(', ')
    out(`| ${r.rank} | ${name(r.buildId)} | ${r.match}% | ${raceNames} | ${r.dualSpec ? name(r.dualSpec.buildId) : '—'} |`)
  }
  const tail = result.results.at(-1)
  out()
  out(
    `Lowest: ${tail ? `${name(tail.buildId)} ${tail.match}%` : '—'} · excluded: ${result.excluded.length}` +
      (result.whyNot.length ? ` · why not: ${result.whyNot.map((w) => name(w.buildId)).join(', ')}` : ''),
  )
  out()
  summary.push(
    `${p.id.padEnd(24)} ${result.results
      .slice(0, 5)
      .map((r) => `${r.buildId}:${r.match}`)
      .join('  ')}  | last ${tail?.match ?? '-'}`,
  )
}
out('## Score basis per build')
out()
for (const b of data.builds) out(`- **${b.name}** (${b.confidence}): ${b.scoreBasis}`)
out()

const target = fileURLToPath(new URL('../docs/SCORES_REVIEW.md', import.meta.url))
writeFileSync(target, lines.join('\n'))
console.log(`Wrote ${target}`)
if (process.argv.includes('--print')) console.log(summary.join('\n'))
